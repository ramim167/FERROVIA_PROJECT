CREATE TABLE TRIP_SEATS
(
    TRIP_SEAT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRIP_ID NUMBER NOT NULL,
    SEAT_ID NUMBER NOT NULL,
    SEAT_STATUS VARCHAR2(10) DEFAULT 'AVAILABLE' NOT NULL,

