-- ============================================================
-- VIEW 1: LIVE TRAIN STATUS
-- Gives passenger/admin query data:
--   * current trip status
--   * direction
--   * last station left
--   * actual departure time from last station
--   * current delay in minutes
--   * next/current station
-- Schedule values are NEVER shifted by the delay.
-- ============================================================
CREATE OR REPLACE VIEW VW_LIVE_TRAIN_STATUS AS
WITH LAST_DEPARTED AS
(
    SELECT
        TS.TRIP_ID,
        TS.TRIP_STOP_ID,
        TS.STATION_ID,
        TS.STOP_SEQUENCE,
        TS.SCHEDULED_DEPARTURE,
        TS.ACTUAL_DEPARTURE,
        ROW_NUMBER() OVER
        (
            PARTITION BY TS.TRIP_ID
            ORDER BY TS.STOP_SEQUENCE DESC
        ) AS RN
    FROM TRIP_STOPS TS
    WHERE TS.ACTUAL_DEPARTURE IS NOT NULL
),
NEXT_STOP AS
(
    SELECT
        TS.TRIP_ID,
        TS.STATION_ID,
        TS.STOP_SEQUENCE,
        TS.SCHEDULED_ARRIVAL,
        TS.SCHEDULED_DEPARTURE,
        TS.STOP_STATUS,
        ROW_NUMBER() OVER
        (
            PARTITION BY TS.TRIP_ID
            ORDER BY TS.STOP_SEQUENCE
        ) AS RN
    FROM TRIP_STOPS TS
    WHERE TS.STOP_STATUS IN ('UPCOMING','ARRIVED')
)
SELECT
    T.TRIP_ID,
    TR.TRAIN_ID,
    TR.TRAIN_NAME,
    TR.TRAIN_CODE,
    R.ROUTE_ID,
    R.ROUTE_CODE,
    R.DIRECTION,
    T.JOURNEY_DATE,
    T.TRIP_STATUS,
    T.SCHEDULED_DEPARTURE,
    T.SCHEDULED_ARRIVAL,
    T.ACTUAL_DEPARTURE,
    T.ACTUAL_ARRIVAL,

    LS.STATION_ID AS LAST_LEFT_STATION_ID,
    LS.STATION_NAME AS LAST_LEFT_STATION,
    LD.ACTUAL_DEPARTURE AS LAST_LEFT_AT,
    LD.SCHEDULED_DEPARTURE AS LAST_SCHEDULED_DEPARTURE,

    CASE
        WHEN LD.ACTUAL_DEPARTURE IS NULL
          OR LD.SCHEDULED_DEPARTURE IS NULL
        THEN 0
        ELSE GREATEST(
            0,
            ROUND(
                (CAST(LD.ACTUAL_DEPARTURE AS DATE)
                 - CAST(LD.SCHEDULED_DEPARTURE AS DATE)) * 1440
            )
        )
    END AS CURRENT_DELAY_MINUTES,

    NS.STATION_ID AS NEXT_STATION_ID,
    NS.STATION_NAME AS NEXT_STATION,
    NXT.SCHEDULED_ARRIVAL AS NEXT_SCHEDULED_ARRIVAL,
    NXT.SCHEDULED_DEPARTURE AS NEXT_SCHEDULED_DEPARTURE,

    CASE
        WHEN T.SPARE_TRIGGERED_AT IS NULL THEN 0
        ELSE 1
    END AS SPARE_TRIGGERED

FROM TRIPS T
JOIN TRAINS TR
    ON TR.TRAIN_ID = T.TRAIN_ID
JOIN ROUTES R
    ON R.ROUTE_ID = T.ROUTE_ID
LEFT JOIN LAST_DEPARTED LD
    ON LD.TRIP_ID = T.TRIP_ID
   AND LD.RN = 1
LEFT JOIN STATIONS LS
    ON LS.STATION_ID = LD.STATION_ID
LEFT JOIN NEXT_STOP NXT
    ON NXT.TRIP_ID = T.TRIP_ID
   AND NXT.RN = 1
LEFT JOIN STATIONS NS
    ON NS.STATION_ID = NXT.STATION_ID;


