-- ============================================================
-- 20. PAYMENTS
-- ============================================================
CREATE TABLE PAYMENTS
(
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_ID NUMBER NOT NULL,
    TRANSACTION_ID VARCHAR2(80),
    PAYMENT_AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(20) NOT NULL,
    PAYMENT_STATUS VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
    PAYMENT_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_PAYMENTS PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_PAYMENT_BOOKING
        FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CONSTRAINT UQ_PAYMENT_TXN UNIQUE (TRANSACTION_ID),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (PAYMENT_AMOUNT > 0),
    CONSTRAINT CK_PAYMENT_METHOD
        CHECK (PAYMENT_METHOD IN ('CARD','MOBILE_BANKING','BANK_TRANSFER','CASH')),
