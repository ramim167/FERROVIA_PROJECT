
CREATE TABLE USERS
(
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FULL_NAME VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(50) NOT NULL,
    PHONE VARCHAR2(11) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role   VARCHAR2(9) DEFAULT 'PASSENGER' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT pk_users PRIMARY KEY (USER_ID),
    CONSTRAINT uq_user_email UNIQUE (EMAIL),
    CONSTRAINT uq_user_phone UNIQUE (PHONE),
    CONSTRAINT chk_users_role
          CHECK ( ROLE IN ( 'PASSENGER' , 'ADMIN' ) )
);

CREATE TABLE STATIONS
(
    STATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STATION_NAME VARCHAR2(70) NOT NULL,
    CITY VARCHAR2(20) NOT NULL,
    STATION_CODE VARCHAR2(10) NOT NULL,

    CONSTRAINT PK_STATIONS PRIMARY KEY ( STATION_ID),
    CONSTRAINT UQ_STATION_CODE UNIQUE (STATION_CODE)
);

CREATE TABLE TRAINS
(
    TRAIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_NAME VARCHAR2(50) NOT NULL,
    TRAIN_TYPE VARCHAR2(15) NOT NULL,
    TRAIN_CODE VARCHAR2(10) NOT NULL,
    TRAIN_STATUS VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    
    CONSTRAINT PK_TRAIN PRIMARY KEY (TRAIN_ID),
    CONSTRAINT UQ_NAME UNIQUE( TRAIN_NAME),
    CONSTRAINT UQ_CODE UNIQUE(TRAIN_CODE),
    CONSTRAINT CK_STATUS
        CHECK (TRAIN_STATUS IN ('ACTIVE' ,'INACTIVE','CANCELLED'))

);

CREATE TABLE TRAIN_STOPS
(
    TRAIN_STOP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY, 
    TRAIN_ID NUMBER NOT NULL,
    STATION_ID NUMBER NOT NULL,
    STOP_SEQUENCE NUMBER NOT NULL,

    ARRIVAL_TIME VARCHAR2(5),
    DEPARTURE_TIME VARCHAR2(5),
    DISTANCE_TO_NEXT_ST NUMBER(8,2),

    CONSTRAINT PK_TRAIN_STOPS PRIMARY KEY (TRAIN_STOP_ID),
    CONSTRAINT FK_STOP_TRAIN FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT FK_STOP_STATION FOREIGN KEY (STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT UQ_TRAIN_STOP UNIQUE (TRAIN_ID,STOP_SEQUENCE),
    CONSTRAINT UQ_TRAIN_STATION UNIQUE (TRAIN_ID,STATION_ID),
    CONSTRAINT VALID_SQ 
        CHECK(STOP_SEQUENCE>0),
    CONSTRAINT VALID_DISTANCE
        CHECK (
            DISTANCE_TO_NEXT_ST IS NULL
            OR DISTANCE_TO_NEXT_ST>=0
    )
);

CREATE TABLE TRIPS
(
    TRIP_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    JOURNEY_DATE DATE NOT NULL,
    TRIP_STATUS VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL,

    CONSTRAINT PK_TRIP_ID PRIMARY KEY (TRIP_ID),
    CONSTRAINT UQ_JOURNEY_DATE UNIQUE (TRAIN_ID,JOURNEY_DATE),
    CONSTRAINT FK_TRIP_TRAIN FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT CHK_STATUS
        CHECK (
            TRIP_STATUS IN('SCHEDULED','RUNNING','DELAYED','COMPLETED','CANCELLED')
    )
);

CREATE TABLE TRAIN_RUNNING_DAYS
(
    RUNNING_DAY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    DAY_CODE VARCHAR2(3) NOT NULL,
    
    CONSTRAINT PK_RUNNING_DAY_ID PRIMARY KEY (RUNNING_DAY_ID),
    CONSTRAINT FK_TRAIN_ID FOREIGN KEY(TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT UQ_TRAIN_RUNNING_DAY UNIQUE(TRAIN_ID,DAY_CODE),
    CONSTRAINT CHK_DAY_CODE
            CHECK(DAY_CODE IN('SAT','SUN','MON','TUE','WED','THU','FRI'))
);

CREATE TABLE CLASS_TYPES
(
    CLASS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CLASS_NAME VARCHAR2(20) NOT NULL,
    CLASS_CODE VARCHAR2(10) NOT NULL,
    
    CONSTRAINT PK_CLASS_ID PRIMARY KEY (CLASS_ID),
    CONSTRAINT UQ_CLASS_CODE UNIQUE(CLASS_CODE),
    CONSTRAINT UQ_CLASS_NAME UNIQUE(CLASS_NAME),
    CONSTRAINT CK_CLASS_CODE_NAME
        CHECK (
            (CLASS_CODE = 'S_CHAIR' AND CLASS_NAME = 'SHOVAN')
            OR
            (CLASS_CODE = 'SN' AND CLASS_NAME = 'SNIGDHA')
            OR
            (CLASS_CODE = 'F_BERTH' AND CLASS_NAME = 'FIRST CLASS BERTH')
            OR
            (CLASS_CODE = 'AC_B' AND CLASS_NAME = 'AC BERTH')
            OR
            (CLASS_CODE = 'AC_S' AND CLASS_NAME = 'AC SEAT')
            OR
            (CLASS_CODE = 'F_CHAIR' AND CLASS_NAME = 'FIRST CLASS CHAIR')
            OR
            (CLASS_CODE = 'SU' AND CLASS_NAME = 'SULABH')
        )
);


CREATE TABLE COACHES
(
    COACH_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    CLASS_ID NUMBER NOT NULL,
    COACH_CODE VARCHAR2(10) NOT NULL,

    CONSTRAINT PK_COACH_ID PRIMARY KEY (COACH_ID),
    CONSTRAINT FK_COACH_TRAIN FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT FK_COACH_CLASS FOREIGN KEY (CLASS_ID) REFERENCES CLASS_TYPES(CLASS_ID),
    CONSTRAINT UQ_TRAIN_COACH UNIQUE (TRAIN_ID, COACH_CODE)
);

CREATE TABLE TRIP_SEATS
(
    TRIP_SEAT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRIP_ID NUMBER NOT NULL,
    SEAT_ID NUMBER NOT NULL,
    SEAT_STATUS VARCHAR2(10) DEFAULT 'AVAILABLE' NOT NULL,

    CONSTRAINT PK_TRIP_SEAT_ID PRIMARY KEY (TRIP_SEAT_ID),
    CONSTRAINT FK_TRIP_SEAT_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS(TRIP_ID),
    CONSTRAINT FK_TRIP_SEAT_SEAT FOREIGN KEY (SEAT_ID) REFERENCES SEATS(SEAT_ID),
    CONSTRAINT UQ_TRIP_SEAT UNIQUE (TRIP_ID, SEAT_ID),
    CONSTRAINT CK_SEAT_STATUS
        CHECK (
            SEAT_STATUS IN (
                'AVAILABLE',
                'HELD',
                'BOOKED',
                'BLOCKED'
            )
        )
);

CREATE TABLE FARE_RULES
(
    FARE_RULE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    CLASS_ID NUMBER NOT NULL,
    RATE_PER_KM NUMBER(8,2) NOT NULL,
    BASE_FARE NUMBER(8,2) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_FARE_RULE_ID PRIMARY KEY (FARE_RULE_ID),
    CONSTRAINT FK_FARE_RULE_TRAIN FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT FK_FARE_RULE_CLASS FOREIGN KEY (CLASS_ID) REFERENCES CLASS_TYPES(CLASS_ID),
    CONSTRAINT UQ_TRAIN_CLASS_FARE UNIQUE (TRAIN_ID, CLASS_ID),
    CONSTRAINT CK_RATE_PER_KM
        CHECK (RATE_PER_KM > 0),
    CONSTRAINT CK_BASE_FARE
        CHECK (BASE_FARE >= 0)
);


CREATE TABLE BOOKINGS
(
    BOOKING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PNR_NUMBER VARCHAR2(20) NOT NULL,
    USER_ID NUMBER NOT NULL,
    TRIP_ID NUMBER NOT NULL,
    SOURCE_STATION_ID NUMBER NOT NULL,
    DESTINATION_STATION_ID NUMBER NOT NULL,
    CLASS_ID NUMBER NOT NULL,
    BOOKING_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TOTAL_FARE NUMBER(10,2) NOT NULL,
    BOOKING_STATUS VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,

    CONSTRAINT PK_BOOKING_ID PRIMARY KEY (BOOKING_ID),
    CONSTRAINT UQ_PNR_NUMBER UNIQUE (PNR_NUMBER),
    CONSTRAINT FK_BOOKING_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_BOOKING_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS(TRIP_ID),
    CONSTRAINT FK_BOOKING_SOURCE FOREIGN KEY (SOURCE_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT FK_BOOKING_DESTINATION FOREIGN KEY (DESTINATION_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT FK_BOOKING_CLASS FOREIGN KEY (CLASS_ID) REFERENCES CLASS_TYPES(CLASS_ID),
    CONSTRAINT CK_BOOKING_STATIONS CHECK (SOURCE_STATION_ID <> DESTINATION_STATION_ID),
    CONSTRAINT CK_TOTAL_FARE CHECK (TOTAL_FARE >= 0),
    CONSTRAINT CK_BOOKING_STATUS
        CHECK (
            BOOKING_STATUS IN ('PENDING','CONFIRMED','CANCELLED','COMPLETED')
        )
);

CREATE TABLE PASSENGERS
(
    PASSENGER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_ID NUMBER NOT NULL,
    PASSENGER_NAME VARCHAR2(100) NOT NULL,
    AGE NUMBER(3) NOT NULL,
    GENDER VARCHAR2(10) NOT NULL,

    CONSTRAINT PK_PASSENGER_ID PRIMARY KEY (PASSENGER_ID),
    CONSTRAINT FK_PASSENGER_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CONSTRAINT CK_PASSENGER_AGE CHECK (AGE > 0),
    CONSTRAINT CK_PASSENGER_GENDER
        CHECK (
            GENDER IN ('MALE','FEMALE','OTHER')
        )
);

CREATE TABLE TICKETS
(
    TICKET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PASSENGER_ID NUMBER NOT NULL,
    TRIP_SEAT_ID NUMBER NOT NULL,
    TICKET_FARE NUMBER(10,2) NOT NULL,
    TICKET_STATUS VARCHAR2(12) DEFAULT 'CONFIRMED' NOT NULL,

    CONSTRAINT PK_TICKET_ID PRIMARY KEY (TICKET_ID),
    CONSTRAINT FK_TICKET_PASSENGER FOREIGN KEY (PASSENGER_ID) REFERENCES PASSENGERS(PASSENGER_ID),
    CONSTRAINT FK_TICKET_TRIP_SEAT FOREIGN KEY (TRIP_SEAT_ID) REFERENCES TRIP_SEATS(TRIP_SEAT_ID),
    CONSTRAINT UQ_PASSENGER_TICKET UNIQUE (PASSENGER_ID),
    CONSTRAINT UQ_TICKET_TRIP_SEAT UNIQUE (TRIP_SEAT_ID),
    CONSTRAINT CK_TICKET_FARE CHECK (TICKET_FARE >= 0),
    CONSTRAINT CK_TICKET_STATUS
        CHECK (
            TICKET_STATUS IN ('CONFIRMED','CANCELLED','COMPLETED')
        )
);

CREATE TABLE PAYMENTS
(
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_ID NUMBER NOT NULL,
    TRANSACTION_ID VARCHAR2(50),
    PAYMENT_AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(20) NOT NULL,
    PAYMENT_STATUS VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
    PAYMENT_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_PAYMENT_ID PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_PAYMENT_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CONSTRAINT UQ_TRANSACTION_ID UNIQUE (TRANSACTION_ID),
    CONSTRAINT CK_PAYMENT_AMOUNT
        CHECK (PAYMENT_AMOUNT > 0),
    CONSTRAINT CK_PAYMENT_METHOD
        CHECK (
            PAYMENT_METHOD IN ('CARD','MOBILE_BANKING','BANK_TRANSFER', 'CASH')
        ),
    CONSTRAINT CK_PAYMENT_STATUS
        CHECK (
            PAYMENT_STATUS IN ('PENDING','SUCCESSFUL','FAILED','REFUNDED')
        )
);

CREATE TABLE REFUNDS
(
    REFUND_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PAYMENT_ID NUMBER NOT NULL,
    TICKET_ID NUMBER NOT NULL,
    REFUND_AMOUNT NUMBER(10,2) NOT NULL,
    REFUND_STATUS VARCHAR2(12) DEFAULT 'REQUESTED' NOT NULL,
    REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PROCESSED_AT TIMESTAMP,

    CONSTRAINT PK_REFUND_ID
        PRIMARY KEY (REFUND_ID),

    CONSTRAINT FK_REFUND_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENTS(PAYMENT_ID),
    CONSTRAINT FK_REFUND_TICKET FOREIGN KEY (TICKET_ID) REFERENCES TICKETS(TICKET_ID),
    CONSTRAINT UQ_REFUND_TICKET
        UNIQUE (TICKET_ID),
    CONSTRAINT CK_REFUND_AMOUNT
        CHECK (REFUND_AMOUNT > 0),
    CONSTRAINT CK_REFUND_STATUS
        CHECK (
            REFUND_STATUS IN ('REQUESTED','PROCESSING','COMPLETED','REJECTED')
        )
);

CREATE TABLE NOTIFICATIONS
(
    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    BOOKING_ID NUMBER,
    TITLE VARCHAR2(100) NOT NULL,
    MESSAGE VARCHAR2(500) NOT NULL,
    IS_READ NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_NOTIFICATION_ID PRIMARY KEY (NOTIFICATION_ID),
    CONSTRAINT FK_NOTIFICATION_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_NOTIFICATION_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CONSTRAINT CK_NOTIFICATION_READ
        CHECK (IS_READ IN (0, 1))
);


