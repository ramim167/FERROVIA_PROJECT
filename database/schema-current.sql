-- ============================================================
-- 18. SEAT_RESERVATIONS
-- Segment-wise occupancy / hold.
-- Example: seat A1 can be booked Dhaka->Cumilla and again Cumilla->CTG.
-- Overlap rule is checked by backend transaction:
--   new_source_seq < existing_dest_seq
--   AND new_dest_seq > existing_source_seq
-- ============================================================
CREATE TABLE SEAT_RESERVATIONS
(
    RESERVATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_ID NUMBER NOT NULL,
    PASSENGER_ID NUMBER NOT NULL,
    TRIP_SEAT_ID NUMBER NOT NULL,

    SOURCE_STATION_ID NUMBER NOT NULL,
    DESTINATION_STATION_ID NUMBER NOT NULL,
    SOURCE_STOP_SEQUENCE NUMBER NOT NULL,
    DESTINATION_STOP_SEQUENCE NUMBER NOT NULL,

    RESERVATION_STATUS VARCHAR2(10) DEFAULT 'HELD' NOT NULL,
    HELD_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    HOLD_EXPIRES_AT TIMESTAMP,
    BOOKED_AT TIMESTAMP,

    CONSTRAINT PK_SEAT_RESERVATIONS PRIMARY KEY (RESERVATION_ID),
    CONSTRAINT FK_RES_BOOKING
        FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CONSTRAINT FK_RES_PASSENGER
        FOREIGN KEY (PASSENGER_ID) REFERENCES PASSENGERS(PASSENGER_ID),
    CONSTRAINT FK_RES_TRIP_SEAT
        FOREIGN KEY (TRIP_SEAT_ID) REFERENCES TRIP_SEATS(TRIP_SEAT_ID),
    CONSTRAINT FK_RES_SOURCE
        FOREIGN KEY (SOURCE_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT FK_RES_DEST
        FOREIGN KEY (DESTINATION_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT UQ_PASSENGER_RESERVATION UNIQUE (PASSENGER_ID),
    CONSTRAINT CK_RES_STATIONS
        CHECK (SOURCE_STATION_ID <> DESTINATION_STATION_ID),
    CONSTRAINT CK_RES_SEQUENCE
        CHECK (SOURCE_STOP_SEQUENCE < DESTINATION_STOP_SEQUENCE),
    CONSTRAINT CK_RES_HOLD_TIME
        CHECK (HOLD_EXPIRES_AT IS NULL OR HELD_AT IS NULL
               OR HOLD_EXPIRES_AT > HELD_AT),
    CONSTRAINT CK_RES_STATUS
        CHECK (RESERVATION_STATUS IN ('HELD','BOOKED','CANCELLED','EXPIRED'))
);


-- ============================================================
