-- IMPLEMENTATION RULES (BACKEND / OPERATOR FLOW)
-- ============================================================
-- 1) OPERATOR ARRIVED button:
--      UPDATE TRIP_STOPS
--      SET ACTUAL_ARRIVAL = SYSTIMESTAMP,
--          ARRIVAL_MARKED_BY = :operator_id,
--          STOP_STATUS = 'ARRIVED'
--      WHERE TRIP_STOP_ID = :trip_stop_id;
--
-- 2) OPERATOR DEPARTED button:
--      UPDATE TRIP_STOPS
--      SET ACTUAL_DEPARTURE = SYSTIMESTAMP,
--          DEPARTURE_MARKED_BY = :operator_id,
--          STOP_STATUS = 'DEPARTED'
--      WHERE TRIP_STOP_ID = :trip_stop_id;
--
--    Current delay =
--      ACTUAL_DEPARTURE - SCHEDULED_DEPARTURE
--    Schedule of later stations does NOT change.
--
-- 3) When current delay >= TRAINS.SPARE_TRIGGER_DELAY_MIN:
--      * current physical trainset keeps running current trip
--      * reserve SPARE trainset at this route's destination terminal
--        for the next opposite-direction trip
--      * set TRIPS.SPARE_TRIGGERED_AT = SYSTIMESTAMP
--      * create TRAINSET_ASSIGNMENTS row with
--        ASSIGNMENT_TYPE = 'SPARE_REPLACEMENT'
--
-- 4) When delayed train reaches destination:
--      old ACTIVE trainset -> SPARE at destination station
--      reserved trainset remains assigned to next trip
--
-- 5) When next trip starts:
--      RESERVED trainset -> ACTIVE
--      CURRENT_STATION_ID -> NULL
--
-- 6) If delay never reaches the threshold:
--      same physical trainset may operate the next opposite trip.
--
-- 7) Recommended fleet for one two-terminal service:
--      3 physical trainsets total:
--        * 1 currently ACTIVE
--        * 1 SPARE at terminal A
--        * 1 SPARE at terminal B
--      Roles rotate dynamically after delay replacement.
--
-- 8) Segment seat availability query must reject overlapping ACTIVE
--    HELD/BOOKED reservations where:
--      :new_source_seq < existing.DESTINATION_STOP_SEQUENCE
--      AND
--      :new_dest_seq > existing.SOURCE_STOP_SEQUENCE
