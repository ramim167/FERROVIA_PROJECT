-- ============================================================
-- FERROVIA / Railway Nexus
-- Full Oracle Database Schema
-- Purpose:
--   * Passenger booking / ticketing / payment / refund
--   * Same train service in UP and DOWN directions
--   * Physical trainset rotation with terminal spares
--   * Operator-based ARRIVED / DEPARTED updates
--   * Live delay + last station left (no GPS required)
--   * Segment-wise seat reservation
--
-- Target: Oracle Database 12c+ (identity columns)
-- ============================================================

-- IMPORTANT MODEL
-- TRAINS      = public service, e.g. "Suborno Express"
-- TRAINSETS   = physical rakes, e.g. SUB-01, SUB-02, SUB-03
-- ROUTES      = direction-specific service, e.g. UP / DOWN
-- TRIPS       = one dated run of one route
-- TRIP_STOPS  = scheduled + actual station events for one trip


-- ============================================================
-- 1. USERS
-- ============================================================
CREATE TABLE USERS
(
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL,
    PHONE VARCHAR2(20),
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(12) DEFAULT 'PASSENGER' NOT NULL,
    ACCOUNT_STATUS VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UQ_USERS_PHONE UNIQUE (PHONE),
    CONSTRAINT CK_USERS_ROLE
        CHECK (ROLE IN ('PASSENGER','ADMIN','OPERATOR')),
    CONSTRAINT CK_USERS_STATUS
        CHECK (ACCOUNT_STATUS IN ('ACTIVE','SUSPENDED','INACTIVE'))
);


-- ============================================================
-- 2. STATIONS
-- ============================================================
CREATE TABLE STATIONS
(
    STATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STATION_NAME VARCHAR2(100) NOT NULL,
    CITY VARCHAR2(60) NOT NULL,
    STATION_CODE VARCHAR2(10) NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_STATIONS PRIMARY KEY (STATION_ID),
    CONSTRAINT UQ_STATIONS_CODE UNIQUE (STATION_CODE),
    CONSTRAINT CK_STATIONS_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);


-- ============================================================
-- 3. TRAINS (PUBLIC TRAIN SERVICE)
-- Example: Suborno Express
-- ============================================================
CREATE TABLE TRAINS
(
    TRAIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_NAME VARCHAR2(80) NOT NULL,
    TRAIN_TYPE VARCHAR2(30) NOT NULL,
    TRAIN_CODE VARCHAR2(20) NOT NULL,
    TRAIN_STATUS VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,

    -- If current operational delay reaches this value,
    -- reserve a spare trainset for the next opposite-direction trip.
    SPARE_TRIGGER_DELAY_MIN NUMBER(4) DEFAULT 60 NOT NULL,

    CONSTRAINT PK_TRAINS PRIMARY KEY (TRAIN_ID),
    CONSTRAINT UQ_TRAINS_NAME UNIQUE (TRAIN_NAME),
    CONSTRAINT UQ_TRAINS_CODE UNIQUE (TRAIN_CODE),
    CONSTRAINT CK_TRAINS_STATUS
        CHECK (TRAIN_STATUS IN ('ACTIVE','INACTIVE','CANCELLED')),
    CONSTRAINT CK_TRAINS_DELAY_TRIGGER
        CHECK (SPARE_TRIGGER_DELAY_MIN >= 0)
);


-- ============================================================
-- 4. ROUTES
-- One train service can have an UP route and a DOWN route.
-- Passenger never needs to choose UP/DOWN directly; From/To determines it.
-- ============================================================
CREATE TABLE ROUTES
(
    ROUTE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    ROUTE_CODE VARCHAR2(20) NOT NULL,
    DIRECTION VARCHAR2(4) NOT NULL,
    SOURCE_STATION_ID NUMBER NOT NULL,
    DESTINATION_STATION_ID NUMBER NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_ROUTES PRIMARY KEY (ROUTE_ID),
    CONSTRAINT FK_ROUTES_TRAIN
        FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT FK_ROUTES_SOURCE
        FOREIGN KEY (SOURCE_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT FK_ROUTES_DEST
        FOREIGN KEY (DESTINATION_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT UQ_ROUTES_CODE UNIQUE (ROUTE_CODE),
    CONSTRAINT UQ_ROUTE_TRAIN_PAIR UNIQUE (ROUTE_ID, TRAIN_ID),
    CONSTRAINT UQ_TRAIN_DIRECTION UNIQUE (TRAIN_ID, DIRECTION),
    CONSTRAINT CK_ROUTES_DIRECTION CHECK (DIRECTION IN ('UP','DOWN')),
    CONSTRAINT CK_ROUTES_STATIONS
        CHECK (SOURCE_STATION_ID <> DESTINATION_STATION_ID),
    CONSTRAINT CK_ROUTES_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);


-- ============================================================
-- 5. ROUTE_STOPS
-- Master timetable template.
-- Offset is measured in minutes from the route's scheduled departure.
-- Example: Dhaka departure offset 0; Cumilla arrival offset 135.
-- ============================================================
CREATE TABLE ROUTE_STOPS
(
    ROUTE_STOP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROUTE_ID NUMBER NOT NULL,
    STATION_ID NUMBER NOT NULL,
    STOP_SEQUENCE NUMBER NOT NULL,

    ARRIVAL_OFFSET_MIN NUMBER(5),
    DEPARTURE_OFFSET_MIN NUMBER(5),
    DISTANCE_FROM_SOURCE_KM NUMBER(8,2) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_ROUTE_STOPS PRIMARY KEY (ROUTE_STOP_ID),
    CONSTRAINT FK_ROUTE_STOPS_ROUTE
        FOREIGN KEY (ROUTE_ID) REFERENCES ROUTES(ROUTE_ID),
    CONSTRAINT FK_ROUTE_STOPS_STATION
        FOREIGN KEY (STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT UQ_ROUTE_STOP_SEQ UNIQUE (ROUTE_ID, STOP_SEQUENCE),
    CONSTRAINT UQ_ROUTE_STATION UNIQUE (ROUTE_ID, STATION_ID),
    CONSTRAINT CK_ROUTE_STOP_SEQ CHECK (STOP_SEQUENCE > 0),
    CONSTRAINT CK_ROUTE_ARR_OFFSET
        CHECK (ARRIVAL_OFFSET_MIN IS NULL OR ARRIVAL_OFFSET_MIN >= 0),
    CONSTRAINT CK_ROUTE_DEP_OFFSET
        CHECK (DEPARTURE_OFFSET_MIN IS NULL OR DEPARTURE_OFFSET_MIN >= 0),
    CONSTRAINT CK_ROUTE_DISTANCE
        CHECK (DISTANCE_FROM_SOURCE_KM >= 0),
    CONSTRAINT CK_ROUTE_STOP_TIME
        CHECK (ARRIVAL_OFFSET_MIN IS NOT NULL OR DEPARTURE_OFFSET_MIN IS NOT NULL)
);


-- ============================================================
-- 6. TRAIN_RUNNING_DAYS
-- Direction-specific weekly schedule.
-- DEPARTURE_MINUTE: minutes after midnight (0..1439).
-- Example 07:00 = 420.
-- ============================================================
CREATE TABLE TRAIN_RUNNING_DAYS
(
    RUNNING_DAY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROUTE_ID NUMBER NOT NULL,
    DAY_CODE VARCHAR2(3) NOT NULL,
    DEPARTURE_MINUTE NUMBER(4) NOT NULL,

    CONSTRAINT PK_TRAIN_RUNNING_DAYS PRIMARY KEY (RUNNING_DAY_ID),
    CONSTRAINT FK_RUNNING_DAY_ROUTE
        FOREIGN KEY (ROUTE_ID) REFERENCES ROUTES(ROUTE_ID),
    CONSTRAINT UQ_ROUTE_RUNNING_DAY UNIQUE (ROUTE_ID, DAY_CODE),
    CONSTRAINT CK_RUNNING_DAY_CODE
        CHECK (DAY_CODE IN ('SAT','SUN','MON','TUE','WED','THU','FRI')),
    CONSTRAINT CK_DEPARTURE_MINUTE
        CHECK (DEPARTURE_MINUTE BETWEEN 0 AND 1439)
);


-- ============================================================
-- 7. TRAINSETS (PHYSICAL TRAINS / RAKES)
-- Example for Suborno: SUB-01, SUB-02, SUB-03.
-- Spare is a dynamic STATUS, not a permanent property.
-- ============================================================
CREATE TABLE TRAINSETS
(
    TRAINSET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    TRAINSET_CODE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'SPARE' NOT NULL,

    -- Filled when the trainset is standing at a station/terminal.
    -- Normally NULL while ACTIVE and running between stations.
    CURRENT_STATION_ID NUMBER,

    STATUS_UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_TRAINSETS PRIMARY KEY (TRAINSET_ID),
    CONSTRAINT UQ_TRAINSET_TRAIN_PAIR UNIQUE (TRAINSET_ID, TRAIN_ID),
    CONSTRAINT FK_TRAINSETS_TRAIN
        FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID),
    CONSTRAINT FK_TRAINSETS_STATION
        FOREIGN KEY (CURRENT_STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT UQ_TRAINSET_CODE UNIQUE (TRAINSET_CODE),
    CONSTRAINT CK_TRAINSET_STATUS
        CHECK (STATUS IN (
            'ACTIVE',
            'SPARE',
            'RESERVED',
            'MAINTENANCE',
            'OUT_OF_SERVICE'
        ))
);


-- ============================================================
-- 8. TRIPS
-- One actual/scheduled journey on a specific date.
-- Schedule remains fixed even when the train is delayed.
-- ============================================================
CREATE TABLE TRIPS
(
    TRIP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRAIN_ID NUMBER NOT NULL,
    ROUTE_ID NUMBER NOT NULL,
    JOURNEY_DATE DATE NOT NULL,

    SCHEDULED_DEPARTURE TIMESTAMP NOT NULL,
    SCHEDULED_ARRIVAL TIMESTAMP NOT NULL,

    ACTUAL_DEPARTURE TIMESTAMP,
    ACTUAL_ARRIVAL TIMESTAMP,

    TRIP_STATUS VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL,
    OPERATOR_USER_ID NUMBER,

    -- Set once delay threshold has triggered spare reservation.
    SPARE_TRIGGERED_AT TIMESTAMP,

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_TRIPS PRIMARY KEY (TRIP_ID),
    CONSTRAINT UQ_TRIP_TRAIN_PAIR UNIQUE (TRIP_ID, TRAIN_ID),
    CONSTRAINT FK_TRIPS_ROUTE_TRAIN
        FOREIGN KEY (ROUTE_ID, TRAIN_ID)
        REFERENCES ROUTES(ROUTE_ID, TRAIN_ID),
    CONSTRAINT FK_TRIPS_OPERATOR
        FOREIGN KEY (OPERATOR_USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT UQ_TRIP_ROUTE_DEPARTURE
        UNIQUE (ROUTE_ID, SCHEDULED_DEPARTURE),
    CONSTRAINT CK_TRIP_TIME_ORDER
        CHECK (SCHEDULED_ARRIVAL > SCHEDULED_DEPARTURE),
    CONSTRAINT CK_TRIP_STATUS
        CHECK (TRIP_STATUS IN (
            'SCHEDULED',
            'BOARDING',
            'RUNNING',
            'DELAYED',
            'COMPLETED',
            'CANCELLED'
        ))
);


-- ============================================================
-- 9. TRAINSET_ASSIGNMENTS
-- Keeps history of which physical trainset operated / will operate a trip.
-- Delay replacement is recorded here.
-- ============================================================
CREATE TABLE TRAINSET_ASSIGNMENTS
(
    ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRIP_ID NUMBER NOT NULL,
    TRAINSET_ID NUMBER NOT NULL,
    TRAIN_ID NUMBER NOT NULL,

    ASSIGNMENT_TYPE VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    ASSIGNMENT_STATUS VARCHAR2(12) DEFAULT 'RESERVED' NOT NULL,

    ASSIGNED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTIVATED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    REASON VARCHAR2(250),

    CONSTRAINT PK_TRAINSET_ASSIGNMENTS PRIMARY KEY (ASSIGNMENT_ID),
    CONSTRAINT FK_ASSIGN_TRIP_TRAIN
        FOREIGN KEY (TRIP_ID, TRAIN_ID)
        REFERENCES TRIPS(TRIP_ID, TRAIN_ID),
    CONSTRAINT FK_ASSIGN_SET_TRAIN
        FOREIGN KEY (TRAINSET_ID, TRAIN_ID)
        REFERENCES TRAINSETS(TRAINSET_ID, TRAIN_ID),
    CONSTRAINT CK_ASSIGN_TYPE
        CHECK (ASSIGNMENT_TYPE IN ('NORMAL','SPARE_REPLACEMENT','MANUAL')),
    CONSTRAINT CK_ASSIGN_STATUS
        CHECK (ASSIGNMENT_STATUS IN ('RESERVED','ACTIVE','COMPLETED','CANCELLED'))
);


-- ============================================================
-- 10. TRIP_STOPS
-- Operational tracking table.
-- Operator clicks ARRIVED / DEPARTED; backend writes server timestamp here.
-- This table provides "last station left" and live delay without GPS.
-- ============================================================
CREATE TABLE TRIP_STOPS
(
    TRIP_STOP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRIP_ID NUMBER NOT NULL,
    ROUTE_STOP_ID NUMBER NOT NULL,
    STATION_ID NUMBER NOT NULL,
    STOP_SEQUENCE NUMBER NOT NULL,

    SCHEDULED_ARRIVAL TIMESTAMP,
    SCHEDULED_DEPARTURE TIMESTAMP,
    ACTUAL_ARRIVAL TIMESTAMP,
    ACTUAL_DEPARTURE TIMESTAMP,

    STOP_STATUS VARCHAR2(10) DEFAULT 'UPCOMING' NOT NULL,

    ARRIVAL_MARKED_BY NUMBER,
    DEPARTURE_MARKED_BY NUMBER,

    CONSTRAINT PK_TRIP_STOPS PRIMARY KEY (TRIP_STOP_ID),
    CONSTRAINT FK_TRIP_STOPS_TRIP
        FOREIGN KEY (TRIP_ID) REFERENCES TRIPS(TRIP_ID),
    CONSTRAINT FK_TRIP_STOPS_ROUTE_STOP
        FOREIGN KEY (ROUTE_STOP_ID) REFERENCES ROUTE_STOPS(ROUTE_STOP_ID),
    CONSTRAINT FK_TRIP_STOPS_STATION
        FOREIGN KEY (STATION_ID) REFERENCES STATIONS(STATION_ID),
    CONSTRAINT FK_TRIP_STOP_ARR_USER
        FOREIGN KEY (ARRIVAL_MARKED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_TRIP_STOP_DEP_USER
        FOREIGN KEY (DEPARTURE_MARKED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT UQ_TRIP_STOP_SEQ UNIQUE (TRIP_ID, STOP_SEQUENCE),
    CONSTRAINT UQ_TRIP_STOP_STATION UNIQUE (TRIP_ID, STATION_ID),
    CONSTRAINT UQ_TRIP_ROUTE_STOP UNIQUE (TRIP_ID, ROUTE_STOP_ID),
    CONSTRAINT CK_TRIP_STOP_SEQUENCE CHECK (STOP_SEQUENCE > 0),
    CONSTRAINT CK_TRIP_STOP_STATUS
        CHECK (STOP_STATUS IN ('UPCOMING','ARRIVED','DEPARTED','SKIPPED')),
    CONSTRAINT CK_TRIP_STOP_TIMES
        CHECK (SCHEDULED_ARRIVAL IS NOT NULL OR SCHEDULED_DEPARTURE IS NOT NULL),
    CONSTRAINT CK_TRIP_STOP_SCHED_ORDER
        CHECK (SCHEDULED_ARRIVAL IS NULL OR SCHEDULED_DEPARTURE IS NULL
               OR SCHEDULED_DEPARTURE >= SCHEDULED_ARRIVAL),
    CONSTRAINT CK_TRIP_STOP_ACT_ORDER
        CHECK (ACTUAL_ARRIVAL IS NULL OR ACTUAL_DEPARTURE IS NULL
               OR ACTUAL_DEPARTURE >= ACTUAL_ARRIVAL)
);


-- ============================================================
-- 11. CLASS_TYPES
